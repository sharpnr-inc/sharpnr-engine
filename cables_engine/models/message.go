package cables_engine_models

import (
	cablesEngineConstants "sharpnr-engine/cables_engine/constants"
	"time"

	"github.com/google/uuid"
	"gorm.io/datatypes"
	"gorm.io/gorm"
)

// CablesMessage — the hot table. Everything here is shaped around one query:
//
//	SELECT ... FROM cables_engine.cables_messages
//	WHERE conversation_id = ? AND seq < ?   -- cursor
//	ORDER BY seq DESC LIMIT 50
//
// so the primary read index is (conversation_id, seq DESC).
//
// indexes:
//
//	unique (conversation_id, seq)
//	index  (conversation_id, seq DESC) where deleted_at is null
//	index  (parent_message_id, seq)                 -- thread view
//	unique (conversation_id, client_message_id)     -- send idempotency
//	GIN    (search_vector)                          -- added in a later migration
type CablesMessage struct {
	ID             uuid.UUID
	OrganizationID uuid.UUID
	ConversationID uuid.UUID

	// Seq is per-conversation and gap-free-ish: taken from
	// conversation.last_seq via an atomic UPDATE ... RETURNING inside the send
	// transaction. It is the cursor for pagination, the basis of unread counts,
	// and the tie-breaker created_at can't be (two sends in the same ms).
	Seq int64

	// Null for SYSTEM messages that nobody authored.
	SenderMemberID *uuid.UUID

	Type    cablesEngineConstants.MessageType
	SubType *cablesEngineConstants.MessageSubType // only for Type == SYSTEM

	// Body is the plain-text rendering — used for search, notifications, and the
	// sidebar preview. Content is the structured version (rich text blocks,
	// code blocks, link previews) the client actually renders. Keeping both
	// means a client that can't parse blocks still shows something readable.
	Body    string
	Content datatypes.JSON

	// ---- threading ----
	// ParentMessageID points at the *root* message of a thread (one level deep,
	// like slack — not a tree). Root messages have it null.
	ParentMessageID *uuid.UUID
	// ReplyToMessageID is the quote/inline-reply pointer, independent of threads.
	ReplyToMessageID *uuid.UUID
	// Only maintained on root messages, so the channel view can render
	// "12 replies · last reply 2h ago" without a subquery.
	ReplyCount      int
	LastReplyAt     *time.Time
	ThreadBroadcast bool // reply also shown in the main channel

	// ClientMessageID is generated by the sender's client before the request.
	// Unique per conversation, so a retry after a dropped websocket doesn't
	// double-post, and the optimistic bubble can be reconciled to the real row.
	ClientMessageID *string

	// ---- denormalized counters, so rendering a page of messages is one query ----
	HasAttachments  bool
	AttachmentCount int
	ReactionCount   int
	IsPinned        bool

	// ---- edit / delete ----
	// Deleting is soft and keeps the row so seq stays stable and threads don't
	// break; the service blanks Body/Content and marks DeletedBy.
	IsEdited  bool
	EditedAt  *time.Time
	DeletedBy *uuid.UUID

	CreatedAt time.Time
	UpdatedAt time.Time
	DeletedAt gorm.DeletedAt
}

func (t *CablesMessage) TableName() string {
	return "cables_engine.cables_messages"
}

