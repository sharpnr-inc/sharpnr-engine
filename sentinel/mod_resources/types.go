// Package sentinelOwnResources is the Sentinel module's own mod_resources: the
// authorization system is itself a protectable resource, so policy authoring,
// role management and group management get Cedar resource types and actions
// like any other module.
//
// These are the actions that close the escalation hole. Without them enforced,
// any authenticated employee can author `permit(principal, action, resource)`
// and attach it to themselves.
package sentinelOwnResources

// Cedar entity types of the Sentinel module's own resources. All three are
// organization-level — they sit under no container.
const (
	ResourceTypeSentinelPolicy = "SentinelPolicy"
	ResourceTypeSentinelRole   = "SentinelRole"
	ResourceTypeSentinelGroup  = "SentinelGroup"
)

// Cedar action ids.
//
// Every id embeds its resource type, which is what keeps them unique in Cedar's
// flat global action namespace — there is no resource qualifier on an action, so
// a bare "canView" registered by two modules would let a policy meant for one
// reach the other. The four CRUD ids per type are generated by
// contracts.Standard(); they are spelled out here so the module's own guard
// calls have constants to reference, and actions_test.go asserts the two agree.
//
// ⚠ These ids are embedded in stored policy text once released. Renaming one
// silently breaks every policy that mentions it — at that point add it to the
// aggregator's grandfatheredActions instead.

// SentinelPolicy.
const (
	ActionCanViewSentinelPolicy    = "canViewSentinelPolicy"
	ActionCanCreateSentinelPolicy  = "canCreateSentinelPolicy"
	ActionCanEditSentinelPolicy    = "canEditSentinelPolicy"
	ActionCanDeleteSentinelPolicy  = "canDeleteSentinelPolicy"
	ActionCanEnableSentinelPolicy  = "canEnableSentinelPolicy"
	ActionCanDisableSentinelPolicy = "canDisableSentinelPolicy"
)

// SentinelRole.
const (
	ActionCanViewSentinelRole           = "canViewSentinelRole"
	ActionCanCreateSentinelRole         = "canCreateSentinelRole"
	ActionCanEditSentinelRole           = "canEditSentinelRole"
	ActionCanDeleteSentinelRole         = "canDeleteSentinelRole"
	ActionCanAssignSentinelRole         = "canAssignSentinelRole"
	ActionCanSetSentinelRolePermissions = "canSetSentinelRolePermissions"
)

// SentinelGroup.
const (
	ActionCanViewSentinelGroup           = "canViewSentinelGroup"
	ActionCanCreateSentinelGroup         = "canCreateSentinelGroup"
	ActionCanEditSentinelGroup           = "canEditSentinelGroup"
	ActionCanDeleteSentinelGroup         = "canDeleteSentinelGroup"
	ActionCanManageSentinelGroupMembers  = "canManageSentinelGroupMembers"
	ActionCanSetSentinelGroupPermissions = "canSetSentinelGroupPermissions"
)

// Organization-wide permissions are not a resource of their own: setting them
// is editing the organization's own grant, guarded by this action.
const ActionCanSetOrganizationPermissions = "canSetSentinelPolicyOrganizationWide"
