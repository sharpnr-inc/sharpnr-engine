package sentinelAggregatorContracts

import (
	"fmt"
	"strings"

	sentinelAggregatorTypes "sharpnr-engine/sentinel_aggregators/types"
)

// Fluent construction of a ResourceRegistration.
//
// This exists because of an observed fact about this codebase: seven modules
// had a mod_resources directory created and left empty. Registering a resource
// meant hand-writing a descriptor, four or more action descriptors with labels
// and RequiresInstance flags, attribute descriptors with operators, and a
// lister. Nobody did that seven times.
//
// Standard() generates the parts that are the same everywhere and leaves the
// module to declare only what is genuinely its own.

/* -------------------------------------------------------------------------- */
/*                                  Actions                                   */
/* -------------------------------------------------------------------------- */

// CRUD verbs generated by Standard(), in the order they should appear in the UI.
var standardVerbs = []struct {
	verb     string
	label    string
	instance bool
}{
	{"View", "View", true},
	{"Create", "Add a new", false},
	{"Edit", "Edit", true},
	{"Delete", "Delete", true},
}

// ActionBuilder builds one ActionDescriptor.
type ActionBuilder struct{ a ActionDescriptor }

// Action declares a module-specific action. Name must be the Cedar action id.
func Action(name, label string) *ActionBuilder {
	return &ActionBuilder{a: ActionDescriptor{Name: name, Label: label}}
}

func (b *ActionBuilder) Describe(d string) *ActionBuilder { b.a.Description = d; return b }

// OnInstance marks the action as targeting one instance rather than the type.
// Without it the action is type-level and can never be narrowed by scoping.
func (b *ActionBuilder) OnInstance() *ActionBuilder { b.a.RequiresInstance = true; return b }

/* -------------------------------------------------------------------------- */
/*                                Attributes                                  */
/* -------------------------------------------------------------------------- */

// AttrBuilder builds one AttributeDescriptor.
type AttrBuilder struct {
	a             AttributeDescriptor
	resolveValues ValueResolver
}

// Attr declares an attribute a policy condition may test. Key must match what
// the resource's FactResolver returns.
func Attr(key string, t sentinelAggregatorTypes.AttrType, label string) *AttrBuilder {
	return &AttrBuilder{a: AttributeDescriptor{
		Key:       key,
		Label:     label,
		Type:      t,
		Operators: sentinelAggregatorTypes.DefaultOperators(t),
	}}
}

func (b *AttrBuilder) Describe(d string) *AttrBuilder { b.a.Description = d; return b }

// Values pins the attribute to a closed set, which the builder renders as a
// picker instead of a text box. Strongly preferred — see AttributeDescriptor.
func (b *AttrBuilder) Values(values ...AttributeValue) *AttrBuilder {
	b.a.Values = append(b.a.Values, values...)
	return b
}

// Value is shorthand for a value whose label is its own text.
func Value(v string) AttributeValue { return AttributeValue{Value: v, Label: v} }

// LabelledValue is a value shown under a different label.
func LabelledValue(v, label string) AttributeValue {
	return AttributeValue{Value: v, Label: label}
}

// ResolveValues supplies the attribute's value list per organization, for values
// that are data rather than constants. Prefer this over leaving an attribute
// free-form — see AttributeDescriptor.Values.
func (b *AttrBuilder) ResolveValues(r ValueResolver) *AttrBuilder {
	b.resolveValues = r
	return b
}

// Operators overrides the default operator set for the attribute's type.
func (b *AttrBuilder) Operators(ops ...sentinelAggregatorTypes.Operator) *AttrBuilder {
	b.a.Operators = ops
	return b
}

/* -------------------------------------------------------------------------- */
/*                                 Resource                                   */
/* -------------------------------------------------------------------------- */

// Builder assembles a ResourceRegistration.
type Builder struct {
	reg       ResourceRegistration
	noDefault bool
	extra     []ActionDescriptor
}

// Standard begins a registration with the four usual CRUD actions generated:
// canView<Type>, canCreate<Type>, canEdit<Type> and canDelete<Type>, each with
// a label and the right RequiresInstance flag.
//
// Generated names follow can<Verb><ResourceType> by construction, which makes
// them collision-free in Cedar's flat global action namespace — the bootstrap
// collision check becomes a backstop rather than the only defence.
//
// label is the plural, human name ("Properties"); it is what an administrator
// reads, so write it for them, not for a developer.
func Standard(resourceType, label string) *Builder {
	return &Builder{reg: ResourceRegistration{
		Descriptor: ResourceDescriptor{Type: resourceType, Label: label},
	}}
}

// Custom begins a registration with NO generated actions, for a resource whose
// verbs are not CRUD at all.
func Custom(resourceType, label string) *Builder {
	b := Standard(resourceType, label)
	b.noDefault = true
	return b
}

func (b *Builder) Category(c string) *Builder { b.reg.Descriptor.Category = c; return b }
func (b *Builder) Describe(d string) *Builder { b.reg.Descriptor.Description = d; return b }

// HousedIn declares the container this resource sits in, and how to find which
// instance of it a given instance belongs to.
//
// Scoping a policy to a container then covers everything beneath it: Cedar's
// `in` is transitive, so a rule naming a Property reaches the hotel inside it
// and the rooms inside that.
func (b *Builder) HousedIn(containerType string, resolve ContainerResolver) *Builder {
	b.reg.HousedIn = containerType
	b.reg.Descriptor.HousedIn = containerType
	b.reg.ResolveContainer = resolve
	return b
}

// WithActions adds module-specific actions alongside the generated ones.
func (b *Builder) WithActions(actions ...*ActionBuilder) *Builder {
	for _, a := range actions {
		b.extra = append(b.extra, a.a)
	}
	return b
}

// WithAttributes declares the attributes conditions may test. Declaring any
// makes ResolveFacts mandatory — the aggregator panics at bootstrap otherwise.
func (b *Builder) WithAttributes(attrs ...*AttrBuilder) *Builder {
	for _, a := range attrs {
		d := a.a
		d.Cedar = "resource." + d.Key
		b.reg.Descriptor.Attributes = append(b.reg.Descriptor.Attributes, d)
		if a.resolveValues != nil {
			if b.reg.ResolveValues == nil {
				b.reg.ResolveValues = map[string]ValueResolver{}
			}
			b.reg.ResolveValues[d.Key] = a.resolveValues
		}
	}
	return b
}

// ResolveFacts supplies the owning org and attribute values for instances.
func (b *Builder) ResolveFacts(r FactResolver) *Builder { b.reg.ResolveFacts = r; return b }

// ListInstances supplies the instance picker. Leave unset for types nobody
// scopes a policy to directly.
func (b *Builder) ListInstances(l InstanceLister) *Builder {
	b.reg.ListInstances = l
	return b
}

// Build produces the registration. Validation happens at bootstrap, in the
// aggregator, where the whole catalog is visible at once.
func (b *Builder) Build() ResourceRegistration {
	actions := make([]ActionDescriptor, 0, len(standardVerbs)+len(b.extra))
	if !b.noDefault {
		singular := strings.TrimSuffix(b.reg.Descriptor.Label, "s")
		for _, v := range standardVerbs {
			actions = append(actions, ActionDescriptor{
				Name:             StandardActionName(v.verb, b.reg.Descriptor.Type),
				Label:            fmt.Sprintf("%s %s", v.label, strings.ToLower(singular)),
				RequiresInstance: v.instance,
			})
		}
	}
	b.reg.Descriptor.Actions = append(actions, b.extra...)
	return b.reg
}

// StandardActionName is the naming convention: can<Verb><ResourceType>. Exported
// so the bootstrap check and a module's own guard calls agree on one spelling.
func StandardActionName(verb, resourceType string) string {
	return "can" + verb + resourceType
}
